import { constants } from "node:fs";
import { access, copyFile, mkdir, readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const outputArg = args.find((arg) => arg !== "--force");
const outputDir = resolve(rootDir, outputArg ?? "release/mac-vm-build-input");
const markerFileName = ".mac-vm-build-input";
const packageJson = JSON.parse(await readFile(resolve(rootDir, "package.json"), "utf8"));
const macPackageDescription = withOperatingSystem(packageJson.description, "Mac");

const includePaths = [
  "package.json",
  "package-lock.json",
  "tsconfig.json",
  "electron.vite.config.ts",
  "src",
  "build"
];

const instructions = `# Mac VM build input

This folder contains the project inputs needed to build the Mac package from a clean npm install.

On the Mac VM, from this folder:

\`\`\`sh
npm ci
npm run dist:mac
\`\`\`

To copy the generated artifacts into a separate folder:

\`\`\`sh
mkdir -p mac-artifacts
find release -maxdepth 1 -type f \\( -name '*.dmg' -o -name '*.zip' \\) -exec cp -v {} mac-artifacts/ \\;
\`\`\`

The Mac target comes from \`package.json\` and matches the effective electron-builder config:

- targets: \`dmg\`, \`zip\`
- package description: \`${macPackageDescription}\`
- output directory before copying: \`release\`
`;

await assertOutputPathIsSafe(outputDir);
await prepareOutputDir(outputDir);

for (const includePath of includePaths) {
  await copyRecursive(resolve(rootDir, includePath), resolve(outputDir, includePath));
}

await writeMacPackageJson(resolve(outputDir, "package.json"));
await writeFile(resolve(outputDir, "README-mac-vm-build.md"), instructions, "utf8");
await writeFile(resolve(outputDir, markerFileName), "Generated by scripts/prepare-mac-vm-build.mjs\n", "utf8");

console.log(`Mac VM build input written to ${outputDir}`);
console.log("");
console.log("Copy that folder to the Mac VM, then run:");
console.log("  npm ci");
console.log("  npm run dist:mac");
console.log("");
console.log(`Project: ${packageJson.name} ${packageJson.version}`);
console.log(`Mac package description: ${macPackageDescription}`);
console.log("Mac package command: npm run dist:mac");

async function assertOutputPathIsSafe(targetDir) {
  if (targetDir === rootDir) {
    throw new Error("Refusing to use the project root as the output directory.");
  }

  const rel = relative(rootDir, targetDir);
  if (!rel || rel === ".." || rel.startsWith(`..${sep}`)) {
    return;
  }

  for (const includePath of includePaths) {
    const sourcePath = resolve(rootDir, includePath);
    const sourceRel = relative(sourcePath, targetDir);
    if (!sourceRel || (!sourceRel.startsWith("..") && sourceRel !== "..")) {
      throw new Error(`Refusing to write output inside source path: ${includePath}`);
    }
  }
}

async function prepareOutputDir(targetDir) {
  if (await exists(targetDir)) {
    await rm(targetDir, { recursive: true, force: true });
  }

  await mkdir(targetDir, { recursive: true });
}

async function copyRecursive(sourcePath, targetPath) {
  const sourceStat = await stat(sourcePath);

  if (sourceStat.isDirectory()) {
    await mkdir(targetPath, { recursive: true });
    const entries = await readdir(sourcePath, { withFileTypes: true });

    for (const entry of entries) {
      if (shouldSkip(entry.name)) {
        continue;
      }

      await copyRecursive(resolve(sourcePath, entry.name), resolve(targetPath, entry.name));
    }

    return;
  }

  await mkdir(dirname(targetPath), { recursive: true });
  await copyFile(sourcePath, targetPath);
}

async function writeMacPackageJson(packageJsonPath) {
  const packageJson = JSON.parse(await readFile(packageJsonPath, "utf8"));
  packageJson.description = macPackageDescription;
  await writeFile(packageJsonPath, `${JSON.stringify(packageJson, null, 2)}\n`, "utf8");
}

function shouldSkip(name) {
  return name === "node_modules" || name === "dist" || name === "release" || name === ".git" || name === ".idea";
}

function withOperatingSystem(description, operatingSystem) {
  const operatingSystemSuffix = /\s+for\s+(?:Windows|Linux|Mac(?:OS)?)$/i;
  return operatingSystemSuffix.test(description)
    ? description.replace(operatingSystemSuffix, ` for ${operatingSystem}`)
    : `${description} for ${operatingSystem}`;
}

async function exists(path) {
  try {
    await access(path, constants.F_OK);
    return true;
  } catch {
    return false;
  }
}
